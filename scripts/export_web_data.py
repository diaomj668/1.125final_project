"""Export a compact set of Boston-area places to web/places.js for the web page.

Writes web/index.html from web/index.template.html with the data inlined.

Keeps only places that pass the planner's quality filter and lie within the
radius of the default anchor, and only the categories used by the interests.

Usage:
    python scripts/export_web_data.py --data data/raw
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from planner.data import load_businesses  # noqa: E402
from planner.geo import haversine_km  # noqa: E402
from planner.interests import INTEREST_CATEGORIES, interests_for  # noqa: E402
from planner.planner import BOSTON_ANCHOR  # noqa: E402

MARKER = '<script src="places.js"></script>'
RADIUS_KM = 20.0
MIN_RATING = 4.0
MIN_REVIEWS = 5
URL_PREFIX = "https://www.google.com/maps/place//data=!4m2!3m1!1s"
URL_SUFFIX = "?authuser=-1&hl=en&gl=us"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--data", default="data/raw")
    p.add_argument("--template", default=str(ROOT / "web" / "index.template.html"))
    p.add_argument("--out", default=str(ROOT / "web" / "index.html"))
    args = p.parse_args()

    businesses, _ = load_businesses(args.data)
    interests = tuple(INTEREST_CATEGORIES)
    rows = []
    for b in businesses:
        if b.rating < MIN_RATING or b.n_reviews < MIN_REVIEWS:
            continue
        if not interests_for(b, interests):
            continue
        if haversine_km(BOSTON_ANCHOR[0], BOSTON_ANCHOR[1], b.lat, b.lon) > RADIUS_KM:
            continue
        cats = [c for c in b.categories
                if any(c.lower() == x.lower() for lst in INTEREST_CATEGORIES.values() for x in lst)]
        row = {
            "id": b.gmap_id, "name": b.name, "address": b.address,
            "lat": round(b.lat, 6), "lon": round(b.lon, 6), "cats": cats,
            "rating": b.rating, "n": b.n_reviews, "price": b.price,
            "hours": {d: b.hours[d] for d in b.hours if b.hours[d] is not None},
        }
        expected = f"{URL_PREFIX}{b.gmap_id}{URL_SUFFIX}"
        if b.url != expected:
            row["url"] = b.url
        rows.append(row)

    data = ("// Generated by scripts/export_web_data.py. Do not edit by hand.\n"
            "window.PLACES = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n")
    template = Path(args.template).read_text(encoding="utf-8")
    if MARKER not in template:
        raise SystemExit(f"marker {MARKER!r} not found in {args.template}")
    # Inline the data so index.html works when opened directly (no separate file needed).
    page = template.replace(MARKER, "<script>\n" + data + "</script>")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    print(f"Wrote {len(rows)} places into {out} ({out.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
